1 实验目的与意义

1.1 课题背景

全国大学生智能车大赛的飞跃雷区任务要求飞行平台在竞赛场地内完成起飞、稳定飞行、跨区域机动及目标相关任务。与地面移动平台相比，四旋翼飞行器具有机动灵活、可跨越障碍等优点，但其动力学具有强耦合、快时变和欠驱动等特点。飞行器的姿态误差会直接影响水平加速度和光流观测，而高度误差又会影响光流比例换算，因此必须建立稳定可靠的飞行控制与状态估计系统。

1.2 设计任务

本项目总体服务于飞跃雷区任务。本人负责飞行控制子系统，具体任务包括：完成主控与各传感器的软件驱动和初始化；实现姿态、高度、速度及位置状态估计；建立姿态、高度和水平位置级联控制；实现四电机混控与安全限幅；建立飞行日志记录与离线分析流程；为后续视觉信标模块提供位置控制接入点。

1.3 设计意义

该系统综合运用了嵌入式系统、自动控制原理、传感器技术、数字信号处理和信息融合等知识。通过对真实飞行数据的反复分析和调参，可形成从传感器标定、状态估计到闭环控制的完整工程实践过程。

2 基础知识与理论

2.1 四旋翼坐标系与姿态表示

机体系规定X轴向前为正、Y轴向右为正、Z轴向上为正。姿态采用滚转角Roll、俯仰角Pitch和偏航角Yaw表示。姿态解算的目标是将陀螺仪角速度积分结果与加速度计重力方向相结合，获得稳定的姿态角，并用于控制及光流补偿。

2.2 Mahony姿态解算

陀螺仪具有短时响应快的优点，但积分会产生漂移；加速度计可在低动态条件下提供重力参考，但易受机动加速度干扰。Mahony算法利用向量误差构成比例—积分校正项，将加速度计观测用于校正陀螺仪积分误差。工程中姿态更新周期设置为2 ms，即500 Hz，以满足姿态内环的实时性要求。

2.3 高度状态估计

高度估计器以高度z和垂直速度vz为状态。预测阶段使用经姿态变换、零偏修正和低通滤波后的世界Z轴加速度；观测阶段利用TOF测距高度修正状态。为降低测距噪声对控制器的直接影响，控制器使用滤波后的高度反馈和垂直速度反馈，而不是直接使用单次测距值。

2.4 光流定位与坐标变换

光流模块输出与地面纹理、飞行高度和姿态相关的像素位移。系统使用外部TOF高度完成尺度换算，并将光流观测映射至机体系。水平位置控制在地球系下计算误差，再依据当前Yaw角旋转为机体系速度误差，最终输出Roll和Pitch控制指令。为避免误调比例参数，光流标定优先采用机体系闭环结果，地球系结果用于评估偏航误差累积的影响。

3 系统总体设计

3.1 硬件组成

系统以CYT4BB7微控制器为核心。ICM42688提供三轴角速度与三轴加速度信息；VL53L8或DL1B模块提供TOF高度信息；LC302模块提供地面光流观测；遥控与串口通信模块用于模式控制和调试；电机驱动模块接收混控后的PWM输出。各模块通过统一状态结构体交换数据，减少模块间直接耦合。


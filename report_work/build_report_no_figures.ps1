4.3 水平速度与位置控制实现

位置外环以目标位置与当前位置之差作为输入，输出目标水平速度；速度内环以目标速度与当前速度之差作为输入，输出目标Roll和Pitch。为了适应起飞阶段和传感器刚有效时的不确定性，系统在位置保持切入前执行制动与权重渐入。进入保持模式时捕获当前位置作为目标点并清除速度环积分项，以减小先前制动过程留下的积分偏置。

4.4 光流补偿与标定

LC302存在模块偏心、光轴与机体系不完全一致、姿态变化引起视场旋转等问题。系统首先完成X/Y轴交换和正负方向映射；其次根据传感器安装位置补偿偏航时绕重心旋转产生的位移；然后利用Roll/Pitch/Yaw角差对光流观测进行经验补偿。调试表明，在大角度手推试验中，姿态补偿能够明显降低运动引起的伪位移。对于低纹理瓷砖地面和光照变化较大的区域，光流质量会下降，系统应降低其可信度或等待视觉信标提供绝对修正。

4.5 视觉信标接口预留

当前视觉模块作为低频辅助信息，不直接替代姿态或光流稳定器。视觉模块输出信标相对偏差和有效标志；在信标有效时，该偏差以小增益、有限幅的形式叠加到位置误差中。后续若已知信标的地图坐标，可构造绝对位置观测对水平状态进行校正，解决纯光流方案长期积分漂移的问题。

5 实验测试与结果分析

5.1 测试方法

测试分为台架静态测试、手持扰动测试和原路返回闭环测试。台架测试验证姿态解算、TOF读数和电机输出方向；手持测试用于识别光流方向、安装偏移与姿态补偿效果；闭环测试按照前推、右移、原路返回的路线执行，通过终点残差评价水平定位的短时闭环性能。所有测试过程保存高度、垂直速度、姿态、光流及控制状态日志，作为参数修改的依据。

5.2 高度估计结果

图4-1显示了记录窗口内TOF测量、EKF高度、控制反馈高度和轨迹参考的关系。TOF测量存在离散噪声，EKF输出相对平滑且能够随高度变化跟踪。结合实际测量记录，TOF高度经姿态补偿后误差可控制在约3 cm以内。图4-2给出了垂直速度估计与参考速度，可用于判断起飞、制动和高度保持阶段的动态特性。

5.3 姿态调试结果

[图：fig_attitude_debug.svg]
图5-1 调试日志中的Roll和Pitch姿态样本

调试日志表明，系统可以连续输出Roll、Pitch与Yaw姿态，并在小幅飞行扰动条件下保持较小的Roll和Pitch角。姿态环参数采用角度环与角速度环分离调节的方式：先在台架条件下确认方向，再通过小油门悬停逐步增加角速度环增益，最后调节角度环响应。该过程避免了直接增大外环增益带来的高频振荡风险。

5.4 光流原路返回结果

[图：fig_position_closure.svg]
图5-2 原路返回试验终点残差

在一次前推、右移、原路返回的测试中，机体系终点残差为X=-1.43 cm、Y=-3.14 cm，说明LC302的方向映射、比例和短时补偿可满足水平控制的基础需求。地球系终点残差为X=1.51 cm、Y=-9.42 cm，误差更大，主要原因是Yaw角参与坐标旋转后会累积航向估计误差。因此，后续比例标定仍应以机体系为主，并引入视觉信标等绝对位置观测修正地球系漂移。

5.5 问题分析

（1）地面纹理与光照直接影响光流质量，低纹理瓷砖地面会导致位移观测不稳定；（2）飞行高度误差会放大到光流比例换算误差；（3）Roll/Pitch接近较大角度时，经验补偿残差增大，需通过倾角阈值降低光流权重；（4）纯光流无法消除长期位置漂移，后续应融合视觉信标、地图或其他绝对定位传感器。

6 总结与展望

6.1 总结

本文面向飞跃雷区任务完成了四旋翼飞行控制子系统设计与实现。系统以CYT4BB7为核心，完成IMU姿态解算、TOF高度估计、光流水平状态估计、级联PID控制和四电机混控。通过多轮日志分析，解决了光流坐标映射、姿态伪位移补偿和位置控制切入冲击等问题。实测结果表明，系统具有稳定的姿态估计、厘米量级的高度测量能力和短时间水平闭环能力。

6.2 展望

后续将完成比赛任务下的视觉信标检测与状态机联调，将信标相对偏差以受限方式接入位置环；在获得信标地图坐标后，进一步构造绝对位置观测并融合进状态估计器；同时完善低纹理和大倾角条件下的传感器可信度判断，提高复杂赛道环境中的稳定性和自主性。


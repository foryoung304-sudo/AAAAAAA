摘  要

面向全国大学生智能车大赛飞跃雷区任务，四旋翼飞行器需要在有限空间内完成稳定起飞、定高、悬停和任务区域机动。为解决低成本传感器在飞行过程中存在噪声、漂移与坐标不一致的问题，本文设计并实现了一套基于CYT4BB7的四旋翼飞行控制系统。系统以ICM42688惯性测量单元为姿态信息源，采用Mahony算法完成姿态解算；以TOF测距传感器提供高度观测，并通过轻量扩展卡尔曼滤波器估计高度和垂直速度；采用LC302光流模块估计水平速度和短时位移，并针对安装偏移、滚转/俯仰和偏航运动引起的伪位移进行补偿。在控制层，设计姿态角—角速度、高度—垂直速度以及位置—速度的多级级联PID控制器，并设置解锁、起飞、悬停切入、限幅和渐入机制。基于飞行日志的测试结果表明，系统的高度测量误差处于厘米量级，原路返回试验中机体系位置闭环残差为(-1.43 cm，-3.14 cm)。研究结果为飞跃雷区任务中的自主飞行与视觉信标辅助导航提供了飞控基础。


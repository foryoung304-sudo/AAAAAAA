图3-1 飞行控制软件总体架构

3.2 软件任务调度

姿态估计、姿态控制和电机输出以2 ms周期运行；高度和光流状态更新以20 ms周期运行；主循环处理高度更新请求、参数菜单、调试打印及日志转储。该设计将高速稳定控制与低速传感器更新分离，避免串口打印等非实时任务影响控制周期。

3.3 飞行模式与安全机制

飞行模式包括锁定、手动/高度保持、位置保持和自动任务模式。位置控制只有在已解锁、光流有效、当前高度满足阈值且垂直速度稳定时才允许进入。控制输出设置限幅、斜坡和渐入权重，防止模式切换时PID积分状态或目标值突变造成大角度指令。

4 飞行控制系统实现

4.1 姿态控制与电机混控

姿态控制采用角度环—角速度环两级PID结构。外环根据期望姿态与反馈姿态生成角速度期望，内环根据角速度误差生成Roll、Pitch和Yaw力矩控制量。混控模块将总油门和三个姿态通道组合为四路电机输出，同时进行上、下移位和限幅处理，以尽量保持姿态控制裕度。油门采用斜坡机制，降低解锁或目标高度切换时的突变。

4.2 高度控制实现

高度控制包含高度轨迹生成、位置外环和垂直速度内环。轨迹模块对目标高度进行限速、限加速度处理，避免指令阶跃；高度外环将高度误差转换为目标垂直速度；垂直速度环根据估计速度调整油门。当前高度估计参数包含加速度增益、低通滤波系数以及高度和速度过程/观测噪声，均通过日志回放和实际飞行记录进行验证。

